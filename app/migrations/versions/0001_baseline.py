def downgrade() -> None:
    # Tables in reverse creation order. Indexes are NOT dropped separately:
    # in SQLite `DROP TABLE` takes its indexes with it, and listing them here
    # by name was an outright bug — 0002 lists exactly the same names
    # (it is the same "CREATE INDEX" list from the old lifespan), so
    # `alembic downgrade base` reached this revision with the indexes already
    # dropped and failed on the very first `DROP INDEX` ("no such index").
    # A missing table is tolerated too: the revision may have been stamped over
    # a database built by create_all() from an older version of the models.
    tables = set(sa.inspect(op.get_bind()).get_table_names())
    for name in _TABLES:
        if name in tables:
            op.drop_table(name)
